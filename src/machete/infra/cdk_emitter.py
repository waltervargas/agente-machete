def _cfn_logical_id(node_id: str) -> str:
    """Convert a node ID to a CloudFormation logical ID."""
    return "".join(part.capitalize() for part in node_id.replace("-", " ").split())


def _class_name(stack_name: str) -> str:
    # Split on non-alpha boundaries, preserving existing CamelCase
    import re

    parts = re.split(r"[-_ ]+", stack_name)
    return "".join(p[0].upper() + p[1:] if p else "" for p in parts)


