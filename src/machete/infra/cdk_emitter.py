"""CDK emitter — functor from ResourceGraph to CDK constructs.

CT mapping:
  - This is a functor: it maps objects (ResourceNodes) and morphisms
    (ResourceEdges) in our free category to objects (CDK Constructs)
    and morphisms (IAM grants, event subscriptions) in the CDK category.
  - It preserves composition: if A → B → C in the graph, the
    corresponding CDK constructs maintain those relationships.
"""

from __future__ import annotations

import json
from typing import Any

from machete.infra.graph import ResourceGraph, ResourceNode, ResourceType


def emit_cdk_json(graph: ResourceGraph, stack_name: str = "MacheteStack") -> dict[str, Any]:
    """Emit a CloudFormation-compatible JSON template from a ResourceGraph.

    This is a simplified emitter that produces a CDK-synthesizable template
    without requiring aws_cdk to be installed. For full CDK synthesis,
    use emit_cdk_app().

    Returns a dict that can be written as a CloudFormation template.
    """
    resources: dict[str, Any] = {}
    outputs: dict[str, Any] = {}

    for node in graph.nodes.values():
        cfn = _node_to_cloudformation(node)
        if cfn:
            resources[_cfn_logical_id(node.id)] = cfn

    # Add edges as IAM policies and event source mappings
    for edge in graph.edges:
        source = graph.get_node(edge.source)
        target = graph.get_node(edge.target)
        if source and target:
            edge_resources = _edge_to_cloudformation(edge, source, target)
            resources.update(edge_resources)

    # Add outputs for API Gateways
    for node in graph.nodes.values():
        if node.type == ResourceType.API_GATEWAY:
            lid = _cfn_logical_id(node.id)
            outputs[f"{lid}Url"] = {
                "Value": {
                    "Fn::Sub": f"https://${{{lid}}}.execute-api.${{AWS::Region}}.amazonaws.com/prod"
                },
                "Description": f"URL for {node.name}",
            }

    return {
        "AWSTemplateFormatVersion": "2010-09-09",
        "Description": f"Machete-generated stack: {stack_name}",
        "Resources": resources,
        "Outputs": outputs,
    }


def emit_cdk_app(graph: ResourceGraph, stack_name: str = "MacheteStack") -> str:
    """Emit a CDK app Python file that can be run with `cdk synth`.

    Returns the Python source code for a CDK app.
    """
    lines = [
        "#!/usr/bin/env python3",
        '"""Auto-generated by Agente Machete — Infrastructure From Code."""',
        "",
        "import aws_cdk as cdk",
        "from aws_cdk import (",
        "    Stack,",
        "    aws_lambda as _lambda,",
        "    aws_apigateway as apigw,",
        "    aws_sqs as sqs,",
        "    aws_dynamodb as dynamodb,",
        "    aws_events as events,",
        "    aws_events_targets as targets,",
        "    aws_iam as iam,",
        "    aws_lambda_event_sources as event_sources,",
        "    Duration,",
        "    RemovalPolicy,",
        ")",
        "from constructs import Construct",
        "",
        "",
        f"class {_class_name(stack_name)}(Stack):",
        "    def __init__(self, scope: Construct, id: str, **kwargs) -> None:",
        "        super().__init__(scope, id, **kwargs)",
        "",
    ]

    # Emit Lambda functions
    for node in graph.nodes.values():
        if node.type == ResourceType.LAMBDA:
            lines.extend(_emit_lambda(node))
            lines.append("")

    # Emit API Gateways
    for node in graph.nodes.values():
        if node.type == ResourceType.API_GATEWAY:
            lines.extend(_emit_api_gateway(node, graph))
            lines.append("")

    # Emit SQS queues
    for node in graph.nodes.values():
        if node.type == ResourceType.SQS:
            lines.extend(_emit_sqs(node, graph))
            lines.append("")

    # Emit EventBridge rules
    for node in graph.nodes.values():
        if node.type == ResourceType.EVENTBRIDGE:
            lines.extend(_emit_eventbridge(node, graph))
            lines.append("")

    # App boilerplate
    lines.extend(
        [
            "",
            "app = cdk.App()",
            f'{_class_name(stack_name)}(app, "{stack_name}")',
            "app.synth()",
        ]
    )

    return "\n".join(lines)


