def _node_to_cloudformation(node: ResourceNode) -> dict[str, Any] | None:
    match node.type:
        case ResourceType.LAMBDA:
            return {
                "Type": "AWS::Lambda::Function",
                "Properties": {
                    "FunctionName": node.name,
                    "Handler": node.properties.get("handler", "index.handler"),
                    "Runtime": node.properties.get("runtime", "python3.11"),
                    "Timeout": node.properties.get("timeout", 60),
                    "MemorySize": node.properties.get("memory", 256),
                    "Environment": {
                        "Variables": node.properties.get("environment", {}),
                    },
                    "Code": {"ZipFile": "# Placeholder — deploy with machete deploy"},
                },
            }
        case ResourceType.API_GATEWAY:
            return {
                "Type": "AWS::ApiGateway::RestApi",
                "Properties": {
                    "Name": node.name,
                    "Description": node.properties.get("description", ""),
                },
            }
        case ResourceType.SQS:
            return {
                "Type": "AWS::SQS::Queue",
                "Properties": {
                    "QueueName": node.name,
                    "VisibilityTimeout": node.properties.get("visibility_timeout", 30),
                },
            }
        case ResourceType.EVENTBRIDGE:
            schedule = node.properties.get("schedule_expression", "rate(1 hour)")
            return {
                "Type": "AWS::Events::Rule",
                "Properties": {
                    "Name": node.name,
                    "ScheduleExpression": schedule,
                    "State": "ENABLED",
                },
            }
        case ResourceType.IAM_ROLE:
            return {
                "Type": "AWS::IAM::Role",
                "Properties": {
                    "RoleName": node.name,
                    "AssumeRolePolicyDocument": {
                        "Version": "2012-10-17",
                        "Statement": [
                            {
                                "Effect": "Allow",
                                "Principal": {
                                    "Service": node.properties.get(
                                        "assume_role_service", "lambda.amazonaws.com"
                                    )
                                },
                                "Action": "sts:AssumeRole",
                            }
                        ],
                    },
                },
            }
        case _:
            return None


